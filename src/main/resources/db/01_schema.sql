    status               VARCHAR2(30) DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED', 'OVERDUE')),
    due_date             TIMESTAMP NOT NULL,
