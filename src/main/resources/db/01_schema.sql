CREATE INDEX idx_act_entity ON ACTIVITY_LOGS(entity_type, entity_id);

-- 14. PRODUCTS TABLE
CREATE TABLE PRODUCTS (
    product_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                  VARCHAR2(60) NOT NULL UNIQUE,
    name                 VARCHAR2(200) NOT NULL,
    description          VARCHAR2(1000),
    category             VARCHAR2(60) NOT NULL,
    cost_price           NUMBER(12,2) NOT NULL CHECK (cost_price >= 0),
    min_selling_price    NUMBER(12,2) NOT NULL,
    max_selling_price    NUMBER(12,2) NOT NULL,
    current_selling_price NUMBER(12,2) NOT NULL,
    status               VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'DISCONTINUED')),
    created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_prod_min_cost CHECK (min_selling_price >= cost_price),
    CONSTRAINT chk_prod_max_min CHECK (max_selling_price >= min_selling_price),
    CONSTRAINT chk_prod_curr CHECK (current_selling_price >= min_selling_price AND current_selling_price <= max_selling_price)
);
CREATE INDEX idx_prod_cat ON PRODUCTS(category);
CREATE INDEX idx_prod_name ON PRODUCTS(name);

-- 15. PRODUCT_VARIANTS TABLE
CREATE TABLE PRODUCT_VARIANTS (
    variant_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id           NUMBER NOT NULL,
    sku                  VARCHAR2(60) NOT NULL UNIQUE,
    variant_name         VARCHAR2(100) NOT NULL,
    attribute_value      VARCHAR2(100) NOT NULL,
    additional_price     NUMBER(12,2) DEFAULT 0 CHECK (additional_price >= 0),
    status               VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT fk_pv_product FOREIGN KEY (product_id) REFERENCES PRODUCTS(product_id) ON DELETE CASCADE
);

-- 16. INVENTORY TABLE
CREATE TABLE INVENTORY (
    inventory_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id           NUMBER NOT NULL UNIQUE,
    available_stock      NUMBER DEFAULT 0 NOT NULL CHECK (available_stock >= 0),
    reserved_stock       NUMBER DEFAULT 0 NOT NULL CHECK (reserved_stock >= 0),
    reorder_threshold    NUMBER DEFAULT 10 NOT NULL CHECK (reorder_threshold >= 0),
    warehouse_location   VARCHAR2(100) DEFAULT 'MAIN-WAREHOUSE',
    updated_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_inv_product FOREIGN KEY (product_id) REFERENCES PRODUCTS(product_id) ON DELETE CASCADE
