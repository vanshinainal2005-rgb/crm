-- 13. ACTIVITY_LOGS TABLE (Timeline of communication & notes)
CREATE TABLE ACTIVITY_LOGS (
    activity_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type          VARCHAR2(50) NOT NULL CHECK (entity_type IN ('CUSTOMER', 'LEAD', 'OPPORTUNITY', 'ORDER', 'INVOICE', 'SYSTEM')),
    entity_id            NUMBER NOT NULL,
