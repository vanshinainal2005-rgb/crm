    notes                CLOB,
    created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cust_employee FOREIGN KEY (assigned_employee_id) REFERENCES USERS(user_id) ON DELETE SET NULL
);
CREATE INDEX idx_cust_norm_phone ON CUSTOMERS(normalized_phone);
CREATE INDEX idx_cust_email ON CUSTOMERS(email);
CREATE INDEX idx_cust_emp ON CUSTOMERS(assigned_employee_id);

-- 8. CONTACTS TABLE (Individual representatives for a customer)
