    deal_value           NUMBER(12,2) DEFAULT 0 NOT NULL,
    probability          NUMBER(5,2) DEFAULT 10 NOT NULL,
    expected_close_date  DATE,
    assigned_to          NUMBER,
    lost_reason          VARCHAR2(255),
    next_follow_up       TIMESTAMP,
    created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_opp_cust FOREIGN KEY (customer_id) REFERENCES CUSTOMERS(customer_id) ON DELETE CASCADE,
    CONSTRAINT fk_opp_lead FOREIGN KEY (lead_id) REFERENCES LEADS(lead_id) ON DELETE SET NULL,
    CONSTRAINT fk_opp_emp FOREIGN KEY (assigned_to) REFERENCES USERS(user_id) ON DELETE SET NULL
);
CREATE INDEX idx_opp_stage ON OPPORTUNITIES(stage);
CREATE INDEX idx_opp_cust ON OPPORTUNITIES(customer_id);

-- 11. OPPORTUNITY_HISTORY TABLE (Audit trail of stage transitions)
CREATE TABLE OPPORTUNITY_HISTORY (
