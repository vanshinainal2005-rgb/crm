-- 1. DROP EXISTING OBJECTS (IN REVERSE DEPENDENCY ORDER)
BEGIN
    FOR cur_rec IN (
        SELECT object_name, object_type 
        FROM user_objects 
        WHERE object_type IN ('TABLE', 'VIEW', 'PACKAGE', 'SEQUENCE')
          AND object_name NOT LIKE 'BIN$%'
    ) LOOP
        BEGIN
            IF cur_rec.object_type = 'TABLE' THEN
                EXECUTE IMMEDIATE 'DROP TABLE "' || cur_rec.object_name || '" CASCADE CONSTRAINTS PURGE';
            ELSIF cur_rec.object_type = 'VIEW' THEN
                EXECUTE IMMEDIATE 'DROP VIEW "' || cur_rec.object_name || '"';
            ELSIF cur_rec.object_type = 'PACKAGE' THEN
                EXECUTE IMMEDIATE 'DROP PACKAGE "' || cur_rec.object_name || '"';
            ELSIF cur_rec.object_type = 'SEQUENCE' THEN
                EXECUTE IMMEDIATE 'DROP SEQUENCE "' || cur_rec.object_name || '"';
            END IF;
        EXCEPTION
            WHEN OTHERS THEN NULL;
        END;
    END LOOP;
END;
/

-- 2. ROLES TABLE
CREATE TABLE ROLES (
    role_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name       VARCHAR2(50) NOT NULL UNIQUE,
    display_name    VARCHAR2(100) NOT NULL,
    description     VARCHAR2(255),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 3. PERMISSIONS TABLE
CREATE TABLE PERMISSIONS (
    permission_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_key  VARCHAR2(100) NOT NULL UNIQUE,
    module_name     VARCHAR2(50) NOT NULL,
    description     VARCHAR2(255)
);

-- 4. ROLE_PERMISSIONS TABLE
CREATE TABLE ROLE_PERMISSIONS (
    role_id         NUMBER NOT NULL,
    permission_id   NUMBER NOT NULL,
    PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_rp_role FOREIGN KEY (role_id) REFERENCES ROLES(role_id) ON DELETE CASCADE,
    CONSTRAINT fk_rp_perm FOREIGN KEY (permission_id) REFERENCES PERMISSIONS(permission_id) ON DELETE CASCADE
);

-- 5. USERS TABLE
CREATE TABLE USERS (
    user_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR2(50) NOT NULL UNIQUE,
    password_hash   VARCHAR2(255) NOT NULL,
    full_name       VARCHAR2(120) NOT NULL,
    email           VARCHAR2(120) NOT NULL UNIQUE,
    phone           VARCHAR2(30),
    department      VARCHAR2(50) NOT NULL,
    status          VARCHAR2(20) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE', 'LOCKED')),
    failed_attempts NUMBER DEFAULT 0,
    locked_until    TIMESTAMP,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- 6. USER_ROLES TABLE
CREATE TABLE USER_ROLES (
    user_id         NUMBER NOT NULL,
    role_id         NUMBER NOT NULL,
    PRIMARY KEY (user_id, role_id),
