    CONSTRAINT fk_ur_role FOREIGN KEY (role_id) REFERENCES ROLES(role_id) ON DELETE CASCADE
);

-- 7. CUSTOMERS TABLE
CREATE TABLE CUSTOMERS (
    customer_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code        VARCHAR2(30) NOT NULL UNIQUE,
    name                 VARCHAR2(150) NOT NULL,
    email                VARCHAR2(150) NOT NULL,
    phone                VARCHAR2(40),
    normalized_phone     VARCHAR2(30),
    company              VARCHAR2(150),
    billing_address      VARCHAR2(400),
    shipping_address     VARCHAR2(400),
    customer_category    VARCHAR2(50) DEFAULT 'STANDARD' CHECK (customer_category IN ('STANDARD', 'ENTERPRISE', 'VIP', 'SMB', 'PARTNER')),
    assigned_employee_id NUMBER,
